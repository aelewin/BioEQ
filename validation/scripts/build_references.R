# Build expected_results CSVs from published reference values, plus updated
# manifest.csv and groups.csv counts.
#
# Sources:
#   * Fuglsang 2015, AAPS J (PMID 25288381)  - parallel datasets P1..P11
#       Table I  : Welch-corrected 90% CI (FDA-recommended for unequal variances)
#       Table II : Classical (equal-variance) 90% CI
#       PE is identical in both tables.
#   * Schutz, Labes, Fuglsang 2014, AAPS J (PMID 25212768) - 2x2x2 datasets A..H
#       Table I  : consensus PE and 90% CI from EquivTest, SAS, WinNonlin, R
#                  (Kinetica diverges on imbalanced sets C and H - see notes)

setwd("/Users/tristanchiappetti/Workspace/BioEQ")
exp_dir <- "validation/expected_results"
dir.create(exp_dir, showWarnings = FALSE, recursive = TRUE)

# ---- Helpers --------------------------------------------------------------
write_expected <- function(file, rows) {
  df <- do.call(rbind, lapply(rows, as.data.frame, stringsAsFactors = FALSE))
  utils::write.csv(df, file.path(exp_dir, file), row.names = FALSE)
}

erow <- function(parameter, expected_value, tolerance_value = 0.01,
                 tolerance_type = "absolute", scope = "study", subject = NA,
                 treatment = NA, unit = "%", reference_source, notes = "") {
  list(parameter = parameter, scope = scope, subject = subject,
       treatment = treatment, expected_value = expected_value,
       tolerance_type = tolerance_type, tolerance_value = tolerance_value,
       unit = unit, reference_source = reference_source, notes = notes)
}

