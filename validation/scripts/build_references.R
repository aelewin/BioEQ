mk <- function(group_id, dataset_id, name, design, n_subjects,
               description, citation, data_file, expected_file, status,
               group = "BE", layer = "BE") {
  data.frame(
    dataset_id = dataset_id, group_id = group_id, name = name,
    group = group, layer = layer, design = design, n_subjects = n_subjects,
    description = description, citation = citation,
    data_file = data_file, expected_file = expected_file, status = status,
    stringsAsFactors = FALSE
  )
}

# Parallel rows
parallel_rows <- do.call(rbind, lapply(seq_len(nrow(parallel_tab)), function(i) {
  code <- parallel_tab$code[i]
  data_file_path <- sprintf("datasets/fuglsang_parallel_%s.csv", code)
  full_path <- file.path("validation", data_file_path)
  n <- if (file.exists(full_path)) {
    nrow(utils::read.csv(full_path))
  } else NA_integer_
  mk(
    group_id    = "be_parallel",
    dataset_id  = sprintf("fuglsang_parallel_%s", code),
    name        = sprintf("Fuglsang Parallel %s", code),
    design      = "parallel",
    n_subjects  = n,
    description = sprintf("Reference parallel-design dataset %s from Fuglsang (2015). PE = %.2f%%, 90%% CI Welch = (%.2f, %.2f); classical = (%.2f, %.2f).",
                          code, parallel_tab$pe[i], parallel_tab$wlo[i],
                          parallel_tab$whi[i], parallel_tab$clo[i],
                          parallel_tab$chi[i]),
    citation    = "Fuglsang A. AAPS J. 2015;17(2):417-423 (PMID 25288381, DOI 10.1208/s12248-014-9704-6)",
    data_file   = data_file_path,
    expected_file = sprintf("expected_results/fuglsang_parallel_%s.csv", code),
    status      = "available"
  )
}))

# 2x2x2 rows
cross_rows <- do.call(rbind, lapply(seq_len(nrow(cross_tab)), function(i) {
  code <- cross_tab$code[i]
  data_file_path <- sprintf("datasets/schutz_2x2_%s.csv", code)
  full_path <- file.path("validation", data_file_path)
  n <- if (file.exists(full_path)) {
    length(unique(utils::read.csv(full_path)$Subject))
  } else NA_integer_
  mk(
    group_id    = "be_2x2_crossover",
    dataset_id  = sprintf("schutz_2x2_%s", code),
    name        = sprintf("Schutz 2x2x2 %s", code),
    design      = "2x2x2",
    n_subjects  = n,
    description = sprintf("Reference 2x2x2 crossover dataset %s from Schutz et al. (2014). %s. Consensus PE = %.2f%%, 90%% CI = (%.2f, %.2f).",
                          code, cross_tab$note[i], cross_tab$pe[i],
                          cross_tab$lo[i], cross_tab$hi[i]),
    citation    = "Schutz H, Labes D, Fuglsang A. AAPS J. 2014;16(6):1292-1297 (PMID 25212768, DOI 10.1208/s12248-014-9661-0)",
    data_file   = data_file_path,
    expected_file = sprintf("expected_results/schutz_2x2_%s.csv", code),
    status      = "available"
  )
}))

