         notes = "90% CI upper bound, Welch-Satterthwaite df"),
    erow("CI_lower_classical",  r$clo, reference_source = ref_p,
         notes = "90% CI lower bound, classical equal-variance t-test"),
    erow("CI_upper_classical",  r$chi, reference_source = ref_p,
